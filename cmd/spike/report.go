func cmdTest(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("test", flag.ContinueOnError)
	bin := fs.String("claude", "claude", "claude binary / binary claude")
	model := fs.String("model", "", "model alias or id, empty = default / model, rỗng = mặc định")
	root := fs.String("dir", "", "parent dir for sandboxes, empty = OS temp / thư mục cha cho sandbox, rỗng = temp")
	only := fs.String("only", "", "comma-separated case ids, e.g. T1,T5 / danh sách case, ví dụ T1,T5")
	out := fs.String("out", "docs/spike-report.md", "report path / đường dẫn report")
	samples := fs.String("samples", "docs/spike-samples", "dir for raw NDJSON per case, empty = off / thư mục NDJSON gốc, rỗng = tắt")
	t7 := fs.Duration("t7-wait", 2*time.Minute, "approval deadline used by T7 (Q-5) / deadline approval dùng ở T7")
	turn := fs.Duration("turn-timeout", 4*time.Minute, "max time per turn / thời gian tối đa mỗi turn")
	verbose := fs.Bool("v", false, "debug logs on stderr / log debug ra stderr")
	if err := fs.Parse(args); err != nil {
		return err
	}

	selected := map[string]bool{}
	for _, id := range strings.Split(*only, ",") {
		if id = strings.ToUpper(strings.TrimSpace(id)); id != "" {
			selected[id] = true
		}
	}

	checks := runPreflight(context.Background(), *bin)
	for _, c := range checks {
		if c.Status == checkFail {
			return fmt.Errorf("preflight %s: %s (run `make spike-preflight`)", c.Name, c.Detail)
		}
	}

	env := scenarioEnv{
		ClaudeBin: *bin, Model: *model, SandboxDir: *root, SamplesDir: *samples,
		T7Wait: *t7, TurnLimit: *turn, Log: newLogger(*verbose),
	}
	ctx, stop := signalContext()
	defer stop()

	var results []CaseResult
	for _, s := range scenarios() {
		if len(selected) > 0 && !selected[s.ID] {
			continue
		}
		if ctx.Err() != nil {
			results = append(results, CaseResult{ID: s.ID, Name: s.Name, Answers: s.Answers, Status: StatusSkipped, Notes: []string{"run cancelled"}})
			continue
		}
		fmt.Fprintf(stdout, "%-4s %s … ", s.ID, s.Name)
		c := CaseResult{ID: s.ID, Name: s.Name, Answers: s.Answers, Status: StatusPass}
		began := time.Now()
		if err := runCase(ctx, s, env, &c); err != nil {
			c.fail("harness error: %v", err)
		}
		c.Duration = time.Since(began)
		fmt.Fprintf(stdout, "%s (%s)\n", c.Status, c.Duration.Round(time.Second))
		results = append(results, c)
	}

	report := renderReport(checks, *model, results)
	if err := os.MkdirAll(filepath.Dir(*out), 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(*out, []byte(report), 0o600); err != nil {
		return fmt.Errorf("write report: %w", err)
	}
	fmt.Fprintf(stdout, "\nreport: %s\n", *out)
	if *samples != "" {
		fmt.Fprintf(stdout, "raw samples: %s (review before committing)\n", *samples)
	}
	for _, r := range results {
		if r.Status == StatusFail {
			return errors.New("some cases failed, see the report")
		}
	}
	return nil
}

// runCase isolates a scenario panic so one bad case cannot hide the others' results.
// runCase cô lập panic của một scenario để một case lỗi không làm mất kết quả các case khác.
func runCase(ctx context.Context, s scenario, env scenarioEnv, c *CaseResult) (err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("panic: %v", r)
		}
	}()
	return s.Run(ctx, env, c)
}

func renderReport(checks []check, model string, results []CaseResult) string {
	home, _ := os.UserHomeDir()
	redact := func(s string) string {
		if home != "" {
			s = strings.ReplaceAll(s, home, "~")
		}
		return s
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Spike report — agent-runtime (Go + `claude -p`)\n\n")
	fmt.Fprintf(&b, "Generated by `make spike-test` on %s. Spec: `docs/specs/features/agent-runtime/`.\n\n", time.Now().Format("2006-01-02 15:04 MST"))
	b.WriteString("## Environment\n\n| Item | Value |\n|---|---|\n")
	fmt.Fprintf(&b, "| OS | %s/%s |\n", runtime.GOOS, runtime.GOARCH)
	if model == "" {
		model = "(default)"
	}
	fmt.Fprintf(&b, "| Model | %s |\n", model)
	for _, c := range checks {
		if c.Name == "flags" {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s %s |\n", c.Name, c.Status, escapeCell(redact(c.Detail)))
	}

	counts := map[Status]int{}
	b.WriteString("\n## Summary\n\n| Case | Name | Answers | Status | Time |\n|---|---|---|---|---|\n")
	for _, r := range results {
		counts[r.Status]++
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.ID, r.Name, r.Answers, r.Status, r.Duration.Round(time.Second))
	}
	fmt.Fprintf(&b, "\nPASS %d · FAIL %d · OBSERVED %d · SKIPPED %d\n", counts[StatusPass], counts[StatusFail], counts[StatusObserved], counts[StatusSkipped])

	b.WriteString("\n## Details\n")
	for _, r := range results {
		fmt.Fprintf(&b, "\n### %s — %s (%s)\n\n", r.ID, r.Name, r.Status)
		for _, n := range r.Notes {
			fmt.Fprintf(&b, "- %s\n", redact(n))
		}
		labels := make([]string, 0, len(r.Samples))
		for l := range r.Samples {
			labels = append(labels, l)
		}
		sort.Strings(labels)
		for _, l := range labels {
			fmt.Fprintf(&b, "\n<details><summary>%s</summary>\n\n```json\n%s```\n\n</details>\n", l, redact(r.Samples[l]))
		}
	}
	return b.String()
}

func escapeCell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
